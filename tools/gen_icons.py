#!/usr/bin/env python3
"""Line icons as QML path data (ADR-0057).

Reads every SVG in third_party/lucide/icons (Lucide) and src/ui/icons/custom (ours, drawn on the
same grid), turns each drawing element into SVG path commands on the 24 grid, and writes
src/ui/icons/IconPaths.js: one path per icon, which Icon.qml strokes. With --check it compares
instead of writing and fails when the file is out of date (CTest).

    python tools/gen_icons.py           # after adding or changing an icon
    python tools/gen_icons.py --check
"""

import argparse
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [ROOT / "third_party" / "lucide" / "icons", ROOT / "src" / "ui" / "icons" / "custom"]
OUTPUT = ROOT / "src" / "ui" / "icons" / "IconPaths.js"
NAMESPACE = "{http://www.w3.org/2000/svg}"

HEADER = """\
.pragma library
// Generated by tools/gen_icons.py from third_party/lucide/icons (Lucide, see its BUILDINFO.md) and
// src/ui/icons/custom; do not edit. One SVG path per icon on the 24 grid, to be stroked (ADR-0057).

var paths = {
"""


def number(value: float) -> str:
    text = f"{value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def attribute(element: ElementTree.Element, name: str, default: str | None = None) -> float:
    value = element.get(name, default)
    if value is None:
        raise ValueError(f"<{element.tag.removeprefix(NAMESPACE)}> lacks {name}")
    return float(value)


def points(text: str) -> list[tuple[float, float]]:
    values = [float(v) for v in text.replace(",", " ").split()]
    if not values or len(values) % 2:
        raise ValueError(f"bad points: {text!r}")
    return list(zip(values[0::2], values[1::2]))


def element_path(element: ElementTree.Element) -> str:
    tag = element.tag.removeprefix(NAMESPACE)
    if tag == "path":
        d = element.get("d", "").strip()
        return "M0 0" + d if d.startswith("m") else d
    if tag in ("circle", "ellipse"):
        cx, cy = attribute(element, "cx", "0"), attribute(element, "cy", "0")
        rx = attribute(element, "r" if tag == "circle" else "rx")
        ry = attribute(element, "r" if tag == "circle" else "ry")
        return (f"M{number(cx - rx)} {number(cy)}a{number(rx)} {number(ry)} 0 1 0 {number(2 * rx)} 0"
                f"a{number(rx)} {number(ry)} 0 1 0 {number(-2 * rx)} 0")
    if tag == "rect":
        x, y = attribute(element, "x", "0"), attribute(element, "y", "0")
        w, h = attribute(element, "width"), attribute(element, "height")
        rx = attribute(element, "rx", element.get("ry", "0"))
        ry = attribute(element, "ry", element.get("rx", "0"))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx == 0 or ry == 0:
            return f"M{number(x)} {number(y)}h{number(w)}v{number(h)}h{number(-w)}Z"
        arc = f"a{number(rx)} {number(ry)} 0 0 1"
        return (f"M{number(x + rx)} {number(y)}h{number(w - 2 * rx)}{arc} {number(rx)} {number(ry)}"
                f"v{number(h - 2 * ry)}{arc} {number(-rx)} {number(ry)}"
                f"h{number(2 * rx - w)}{arc} {number(-rx)} {number(-ry)}"
                f"v{number(2 * ry - h)}{arc} {number(rx)} {number(-ry)}Z")
    if tag == "line":
        return (f"M{number(attribute(element, 'x1', '0'))} {number(attribute(element, 'y1', '0'))}"
                f"L{number(attribute(element, 'x2', '0'))} {number(attribute(element, 'y2', '0'))}")
    if tag in ("polyline", "polygon"):
        text = "M" + "L".join(f"{number(px)} {number(py)}" for px, py in points(element.get("points", "")))
        return text + ("Z" if tag == "polygon" else "")
    raise ValueError(f"unsupported element <{tag}>")


def icon_path(file: Path) -> str:
    root = ElementTree.parse(file).getroot()
    if root.get("viewBox", "").split() != ["0", "0", "24", "24"]:
        raise ValueError(f"{file}: not drawn on the 24 grid")
    parts = [element_path(element) for element in root.iter() if element is not root]
    if not parts:
        raise ValueError(f"{file}: nothing to draw")
    return "".join(parts)


def generate() -> tuple[str, int]:
    icons: dict[str, str] = {}
    for source in SOURCES:
        for file in sorted(source.glob("*.svg")) if source.is_dir() else []:
            if file.stem in icons:
                raise ValueError(f"{file}: an icon named {file.stem} exists already")
            icons[file.stem] = icon_path(file)
    lines = [f'    "{name}": "{path}"' for name, path in sorted(icons.items())]
    return HEADER + ",\n".join(lines) + "\n};\n", len(icons)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when IconPaths.js is out of date")
    arguments = parser.parse_args()
    try:
        text, count = generate()
    except (ValueError, ElementTree.ParseError) as error:
        print(f"gen_icons: {error}", file=sys.stderr)
        return 1
    if arguments.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"gen_icons: {OUTPUT.relative_to(ROOT)} is out of date; run python tools/gen_icons.py",
                  file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {count} icons to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
