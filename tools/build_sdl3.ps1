<#
.SYNOPSIS
    Builds the gamepad-only SDL3 of ADR-0075 with MSVC and places it in third_party/sdl3.

.DESCRIPTION
    Run it in a shell prepared by tools/dev-env.ps1 (MSVC, CMake and Ninja on PATH). The source
    release is downloaded once into deps/sdl3/downloads and must match the hash below; it is built
    under deps/sdl3. third_party/sdl3 receives the headers, the import library, the DLL, the license
    and BUILDINFO.md, and is committed.

    Upgrading: change the version and its hash, run this script, run the tests, commit
    third_party/sdl3.

.EXAMPLE
    . .\tools\dev-env.ps1
    .\tools\build_sdl3.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$Sdl = @{
    Name   = 'SDL3-3.4.18'
    Url    = 'https://github.com/libsdl-org/SDL/releases/download/release-3.4.18/SDL3-3.4.18.tar.gz'
    Sha256 = '9c75cf16330322c217dedd2e0609f1124f1b54b8633e763467b4684d0f4334a3'
}

$CMakeFlags = @(
    '-DCMAKE_BUILD_TYPE=Release',
    '-DSDL_SHARED=ON', '-DSDL_STATIC=OFF',
    '-DSDL_TEST_LIBRARY=OFF', '-DSDL_TESTS=OFF', '-DSDL_EXAMPLES=OFF',
    '-DSDL_INSTALL=ON', '-DSDL_INSTALL_DOCS=OFF', '-DSDL_INSTALL_CPACK=OFF',
    '-DSDL_AUDIO=OFF', '-DSDL_VIDEO=OFF', '-DSDL_GPU=OFF', '-DSDL_RENDER=OFF', '-DSDL_CAMERA=OFF',
    '-DSDL_HAPTIC=OFF', '-DSDL_POWER=OFF', '-DSDL_SENSOR=OFF', '-DSDL_DIALOG=OFF', '-DSDL_TRAY=OFF',
    '-DSDL_JOYSTICK=ON', '-DSDL_HIDAPI=ON', '-DSDL_HIDAPI_JOYSTICK=ON', '-DSDL_HIDAPI_LIBUSB=OFF', '-DSDL_XINPUT=ON',
    '-DSDL_VIRTUAL_JOYSTICK=OFF', '-DSDL_OFFSCREEN=OFF', '-DSDL_VULKAN=OFF'
)

$root = Split-Path $PSScriptRoot -Parent
$work = Join-Path $root 'deps\sdl3'
$downloads = Join-Path $work 'downloads'
$sources = Join-Path $work 'src'
$build = Join-Path $work 'build'
$prefix = Join-Path $work 'prefix'
$output = Join-Path $root 'third_party\sdl3'

function Assert-ExitCode([string]$What) {
    if ($LASTEXITCODE -ne 0) { throw "$What failed (exit code $LASTEXITCODE)" }
}

function Reset-Directory([string]$Path) {
    if (Test-Path $Path) { Remove-Item -Recurse -Force $Path }
    New-Item -ItemType Directory -Force $Path | Out-Null
}

function Get-Source([hashtable]$Spec) {
    $file = Join-Path $downloads (Split-Path $Spec.Url -Leaf)
    New-Item -ItemType Directory -Force $downloads | Out-Null
    if (-not (Test-Path $file) -or (Get-FileHash $file -Algorithm SHA256).Hash -ne $Spec.Sha256) {
        Write-Host "Downloading $($Spec.Url)"
        & curl.exe -L --fail --silent --show-error -C - --retry 5 --retry-all-errors -o $file $Spec.Url
    }
    if (-not (Test-Path $file) -or (Get-FileHash $file -Algorithm SHA256).Hash -ne $Spec.Sha256) {
        Remove-Item $file -ErrorAction SilentlyContinue
        throw "$($Spec.Url) did not arrive intact (SHA-256 differs); the partial file was removed, run again"
    }
    return $file
}

foreach ($tool in 'cl.exe', 'cmake', 'ninja') {
    if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) {
        throw "$tool is not on PATH: run . .\tools\dev-env.ps1 first"
    }
}

$archive = Get-Source $Sdl
Reset-Directory $sources
& tar.exe -xzf $archive -C $sources
Assert-ExitCode 'tar (SDL3)'
$source = Join-Path $sources $Sdl.Name

Reset-Directory $build
Reset-Directory $prefix
& cmake -S $source -B $build -G Ninja "-DCMAKE_INSTALL_PREFIX=$prefix" @CMakeFlags
Assert-ExitCode 'cmake configure (SDL3)'
& cmake --build $build
Assert-ExitCode 'cmake build (SDL3)'
& cmake --install $build
Assert-ExitCode 'cmake install (SDL3)'

Reset-Directory $output
foreach ($dir in 'include', 'lib', 'bin', 'licenses') { New-Item -ItemType Directory -Force (Join-Path $output $dir) | Out-Null }
Copy-Item -Recurse (Join-Path $prefix 'include\SDL3') (Join-Path $output 'include')
Copy-Item (Join-Path $prefix 'lib\SDL3.lib') (Join-Path $output 'lib')
Copy-Item (Join-Path $prefix 'bin\SDL3.dll') (Join-Path $output 'bin')
Copy-Item (Join-Path $source 'LICENSE.txt') (Join-Path $output 'licenses\SDL3-LICENSE.txt')

$cmakeVersion = ((& cmake --version) | Select-Object -First 1)
$files = Get-ChildItem -Path (Join-Path $output 'bin'), (Join-Path $output 'lib') -File | Sort-Object FullName
$info = @(
    '# SDL3 build (ADR-0075)'
    ''
    'Generated by `tools/build_sdl3.ps1`; do not edit. Change the script and rebuild instead.'
    ''
    '| Input | Version | SHA-256 |'
    '|---|---|---|'
    "| SDL | $($Sdl.Name) | ``$($Sdl.Sha256.ToLowerInvariant())`` |"
    "| MSVC | $env:VCToolsVersion | |"
    "| CMake | $cmakeVersion | |"
    ''
    'CMake flags (plus `-G Ninja` and `CMAKE_INSTALL_PREFIX`):'
    ''
    '```'
    ($CMakeFlags -join "`n")
    '```'
    ''
    '| File | Bytes | SHA-256 |'
    '|---|---|---|'
)
foreach ($file in $files) {
    $relative = $file.FullName.Substring($output.Length + 1).Replace('\', '/')
    $info += "| $relative | $($file.Length) | ``$((Get-FileHash $file.FullName -Algorithm SHA256).Hash.ToLowerInvariant())`` |"
}
[IO.File]::WriteAllText((Join-Path $output 'BUILDINFO.md'), (($info -join "`n") + "`n"))

Write-Host "SDL3 installed into $output"
$files | ForEach-Object { Write-Host ("  {0,-12} {1,12:N0} bytes" -f $_.Name, $_.Length) }
