const PadModel& padModel(PadFamily family) noexcept
{
    switch (family) {
    case PadFamily::Xbox:
        return kXbox;
    case PadFamily::DualShock4:
        return kDualShock4;
    case PadFamily::DualSense:
        return kDualSense;
    case PadFamily::Generic:
        break;
    }
    return kGeneric;
}

std::vector<std::uint8_t> padInputReport(PadFamily family, const PadPassState& state)
{
    switch (family) {
    case PadFamily::Xbox:
        return xboxReport(state);
    case PadFamily::DualShock4:
        return dualShock4Report(state);
    case PadFamily::DualSense:
        return dualSenseReport(state);
    case PadFamily::Generic:
        break;
    }
    return genericReport(state);
}

std::optional<PadRumble> padRumble(PadFamily family, std::span<const std::uint8_t> output) noexcept
{
    switch (family) {
    case PadFamily::Xbox: {
        if (output.size() < 6 || output[0] != kXboxRumbleReport) {
            return std::nullopt;
        }
        const std::uint8_t enable = output[1];
        return PadRumble{.strong = percentMotor(enable, 0x02, output[4]),
                         .weak = percentMotor(enable, 0x01, output[5]),
                         .leftTrigger = percentMotor(enable, 0x08, output[2]),
                         .rightTrigger = percentMotor(enable, 0x04, output[3])};
    }
    case PadFamily::DualShock4:
        if (output.size() < 6 || output[0] != kDualShock4RumbleReport || (output[1] & 0x01U) == 0) {
            return std::nullopt;
        }
        return PadRumble{.strong = byteMotor(output[5]), .weak = byteMotor(output[4])};
    case PadFamily::DualSense: {
        if (output.size() < 5 || output[0] != kDualSenseRumbleReport) {
            return std::nullopt;
        }
        const bool classic = (output[1] & 0x01U) != 0;
        const bool improved = output.size() > 39 && (output[39] & 0x04U) != 0;
        if (!classic && !improved) {
            return std::nullopt;
        }
        return PadRumble{.strong = byteMotor(output[4]), .weak = byteMotor(output[3])};
    }
    case PadFamily::Generic:
        break;
    }
    return std::nullopt;
}

