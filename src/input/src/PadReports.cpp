template <std::size_t N>
void setButtons(std::vector<std::uint8_t>& report, std::uint32_t buttons, const std::array<ButtonBit, N>& table) noexcept
{
    for (const ButtonBit& entry : table) {
        if ((buttons & entry.button) != 0) {
            report[entry.at] = static_cast<std::uint8_t>(report[entry.at] | entry.bit);
        }
    }
}

void put16(std::vector<std::uint8_t>& report, std::size_t at, std::uint16_t value) noexcept
{
    report[at] = static_cast<std::uint8_t>(value & 0xFFU);
    report[at + 1] = static_cast<std::uint8_t>(value >> 8U);
}

std::uint8_t stick8(std::int16_t value) noexcept
{
    return static_cast<std::uint8_t>((static_cast<int>(value) + 32768) >> 8);
}

std::uint16_t stick16(std::int16_t value) noexcept
{
    return static_cast<std::uint16_t>(static_cast<int>(value) + 32768);
}

std::uint16_t trigger10(std::uint8_t value) noexcept
{
    return static_cast<std::uint16_t>(value * 1023 / 255);
}

std::uint8_t hatFromOne(std::uint8_t hat) noexcept
{
    return hat < kPadHatCentred ? static_cast<std::uint8_t>(hat + 1) : std::uint8_t{0};
}

std::uint8_t hatFromZero(std::uint8_t hat) noexcept
{
    return std::min(hat, kPadHatCentred);
}

std::vector<std::uint8_t> xboxReport(const PadPassState& state)
{
    std::vector<std::uint8_t> report(kXboxInputSize, 0);
    report[0] = kInputReport;
    put16(report, 1, stick16(state.leftX));
    put16(report, 3, stick16(state.leftY));
    put16(report, 5, stick16(state.rightX));
    put16(report, 7, stick16(state.rightY));
    put16(report, 9, trigger10(state.leftTrigger));
    put16(report, 11, trigger10(state.rightTrigger));
    report[13] = hatFromOne(state.hat);
    setButtons(report, state.buttons, kXboxButtons);
    return report;
}

std::vector<std::uint8_t> dualShock4Report(const PadPassState& state)
{
    std::vector<std::uint8_t> report(kSonyInputSize, 0);
    report[0] = kInputReport;
    report[1] = stick8(state.leftX);
    report[2] = stick8(state.leftY);
    report[3] = stick8(state.rightX);
    report[4] = stick8(state.rightY);
    report[5] = hatFromZero(state.hat);
    setButtons(report, state.buttons, kDualShock4Buttons);
    report[8] = state.leftTrigger;
    report[9] = state.rightTrigger;
    report[30] = kDualShock4Status;
    report[33] = 1;
    for (const std::size_t contact : kDualShock4Contacts) {
        report[contact] = kTouchInactive;
    }
    return report;
}

std::vector<std::uint8_t> dualSenseReport(const PadPassState& state)
{
    std::vector<std::uint8_t> report(kSonyInputSize, 0);
    report[0] = kInputReport;
    report[1] = stick8(state.leftX);
    report[2] = stick8(state.leftY);
    report[3] = stick8(state.rightX);
    report[4] = stick8(state.rightY);
    report[5] = state.leftTrigger;
    report[6] = state.rightTrigger;
    report[8] = hatFromZero(state.hat);
    setButtons(report, state.buttons, kDualSenseButtons);
    for (const std::size_t contact : kDualSenseContacts) {
        report[contact] = kTouchInactive;
    }
    report[53] = kDualSenseStatus;
    return report;
}

std::vector<std::uint8_t> genericReport(const PadPassState& state)
{
    std::vector<std::uint8_t> report(kGenericInputSize, 0);
    report[0] = kInputReport;
    put16(report, 1, static_cast<std::uint16_t>(state.buttons & 0xFFFFU));
    report[3] = hatFromOne(state.hat);
    put16(report, 4, static_cast<std::uint16_t>(state.leftX));
    put16(report, 6, static_cast<std::uint16_t>(state.leftY));
    put16(report, 8, static_cast<std::uint16_t>(state.rightX));
    put16(report, 10, static_cast<std::uint16_t>(state.rightY));
    report[12] = state.leftTrigger;
    report[13] = state.rightTrigger;
    return report;
}

std::uint16_t byteMotor(std::uint8_t value) noexcept
{
    return static_cast<std::uint16_t>(value * 257);
}

std::uint16_t percentMotor(std::uint8_t enable, std::uint8_t bit, std::uint8_t value) noexcept
{
    if ((enable & bit) == 0) {
        return 0;
    }
    return static_cast<std::uint16_t>(std::min<int>(value, kXboxMagnitudeMax) * 65535 / kXboxMagnitudeMax);
}

