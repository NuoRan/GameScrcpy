bool plainIdentifier(std::string_view name)
{
    const auto leading = [](char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' || c == '$'; };
    return !name.empty() && leading(name.front())
        && std::all_of(name.begin() + 1, name.end(), [&leading](char c) { return leading(c) || (c >= '0' && c <= '9'); });
}

std::string controlAccess(std::string_view id)
{
    return plainIdentifier(id) ? "controls." + std::string(id) : "controls[" + nlohmann::json(std::string(id)).dump() + "]";
}

