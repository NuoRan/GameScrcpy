int newScriptProject(const fs::path& folder, const std::optional<fs::path>& profile)
{
    std::error_code error;
    if (fs::exists(folder, error) && !fs::is_empty(folder, error)) {
        std::cerr << "gs new: " << utf8(folder) << " is not empty; choose a new folder\n";
        return kUsage;
    }
    if (!profile) {
        const bool written = writeText(folder / "src" / "main.ts", kMainTs)
                          && writeText(folder / "tsconfig.json", script::scriptTsconfig())
                          && writeText(folder / "AGENTS.md", kScriptAgents)
                          && writeText(folder / pathOf(kApiTypesFile), apiDeclarations())
                          && writeText(folder / pathOf(kExtensionTypesFile), extensionDeclarations());
        if (!written) {
            std::cerr << "gs new: cannot write the project files in " << utf8(folder) << '\n';
            return kProblems;
        }
        std::cout << "created " << utf8(folder) << ": src/main.ts, tsconfig.json, AGENTS.md, " << kApiTypesFile
                  << ", " << kExtensionTypesFile << '\n';
        return kSuccess;
    }
    const std::optional<std::string> text = readText(*profile);
    if (!text) {
        std::cerr << "gs new: cannot read " << utf8(*profile) << '\n';
        return kProblems;
    }
    const auto loaded = loadProjectProfile(*profile);
    if (!loaded) {
        printProfileProblems("gs new", loaded.error());
        return kProblems;
    }
    const bool written = writeText(folder / pathOf(kProfileFile), *text)
                      && writeText(folder / "logic.ts", logicTemplate(*loaded))
                      && writeText(folder / "tsconfig.json", script::profileTsconfig())
                      && writeText(folder / "AGENTS.md", kProfileAgents)
                      && writeText(folder / pathOf(kApiTypesFile), apiDeclarations())
                      && writeText(folder / pathOf(kProfileTypesFile), script::profileTypes(loaded->controls, loaded->states))
                      && writeText(folder / pathOf(kExtensionTypesFile), extensionDeclarations());
    if (!written) {
        std::cerr << "gs new: cannot write the profile folder " << utf8(folder) << '\n';
        return kProblems;
    }
    std::cout << "created " << utf8(folder) << ": profile.json, logic.ts, tsconfig.json, AGENTS.md, " << kApiTypesFile
              << ", " << kProfileTypesFile << ", " << kExtensionTypesFile << '\n';
    return kSuccess;
}

int writeProjectTypes(const fs::path& folder)
{
    std::error_code error;
    if (!fs::is_directory(folder, error)) {
        std::cerr << "gs types: " << utf8(folder) << " is not a folder\n";
        return kUsage;
    }
    if (!writeText(folder / pathOf(kApiTypesFile), apiDeclarations())) {
        std::cerr << "gs types: cannot write " << kApiTypesFile << '\n';
        return kProblems;
    }
    if (!writeText(folder / pathOf(kExtensionTypesFile), extensionDeclarations())) {
        std::cerr << "gs types: cannot write " << kExtensionTypesFile << '\n';
        return kProblems;
    }
    if (!isProfileFolder(folder)) {
        std::cout << "wrote " << kApiTypesFile << ", " << kExtensionTypesFile << '\n';
        return kSuccess;
    }
    const auto loaded = loadProjectProfile(folder / pathOf(kProfileFile));
    if (!loaded) {
        printProfileProblems("gs types", loaded.error());
        return kProblems;
    }
    const script::LoadedResources resources = projectResources(folder);
    if (!resources) {
        for (const std::string& problem : resources.error()) {
            std::cerr << "gs types: " << script::kResourcesFile << ' ' << problem << '\n';
        }
        return kProblems;
    }
    if (!writeText(folder / pathOf(kProfileTypesFile),
                   script::profileTypes(loaded->controls, loaded->states, *resources))) {
        std::cerr << "gs types: cannot write " << kProfileTypesFile << '\n';
        return kProblems;
    }
    std::cout << "wrote " << kApiTypesFile << ", " << kProfileTypesFile << ", " << kExtensionTypesFile << '\n';
    return kSuccess;
}

int checkScriptProject(const fs::path& folder, bool json, const std::string& locale)
{
    std::error_code error;
    if (!fs::is_directory(folder, error)) {
        std::cerr << "gs check: " << utf8(folder) << " is not a folder\n";
        return kUsage;
    }
    std::vector<Problem> problems;
    const bool profileFolder = isProfileFolder(folder);
    if (!entryOf(folder)) {
        problems.push_back({profileFolder ? "logic.ts" : "src/main.ts", 0, 0, "error", "GS-CHECK-006",
                            profileFolder ? "the profile folder has no logic.ts or logic.js"
                                          : "the project has no src/main.ts or src/main.js",
                            "check"});
    }
    std::optional<std::string> profileTypes;
    if (profileFolder) {
        const auto loaded = loadProjectProfile(folder / pathOf(kProfileFile));
        if (loaded) {
            const script::LoadedResources resources = projectResources(folder);
            if (!resources) {
                for (const std::string& problem : resources.error()) {
                    problems.push_back(
                        {std::string(script::kResourcesFile), 0, 0, "error", "GS-CHECK-007", problem, "resources"});
                }
            }
            profileTypes = script::profileTypes(loaded->controls, loaded->states,
                                                resources ? *resources : script::Resources{});
        } else {
            for (const std::string& problem : loaded.error()) {
                problems.push_back({std::string(kProfileFile), 0, 0, "error", "GS-CHECK-005", problem, "profile"});
            }
        }
    }
    const std::vector<fs::path> files = sourceFiles(folder);
    sourceProblems(folder, files, problems);
    if (!profileFolder || profileTypes) {
        typeProblems(folder, files, profileTypes, locale, problems);
    }
    return printProblems(problems, json);
}

std::optional<int> runScriptCommand(int argc, wchar_t** argv)
{
    if (argc < 2) {
        return std::nullopt;
    }
    const std::wstring_view verb(argv[1]);
    const std::vector<std::wstring_view> args(argv + 2, argv + argc);
    if (verb == L"new") {
        if (args.size() == 1) {
            return newScriptProject(fs::path(args[0]), std::nullopt);
        }
        if (args.size() == 3 && args[1] == L"--profile") {
            return newScriptProject(fs::path(args[0]), fs::path(args[2]));
        }
        return usage("gs new <folder> [--profile <profile.json>]");
    }
    if (verb == L"check") {
        bool json = false;
        std::string locale;
        bool fine = !args.empty();
        for (std::size_t index = 1; fine && index < args.size(); ++index) {
            if (args[index] == L"--json" && !json) {
                json = true;
            } else if (args[index] == L"--locale" && locale.empty() && index + 1 < args.size()) {
                const std::wstring_view tag = args[++index];
                fine = !tag.empty() && tag.size() <= 16 && std::ranges::all_of(tag, [](wchar_t c) {
                    return (c >= L'a' && c <= L'z') || (c >= L'A' && c <= L'Z') || (c >= L'0' && c <= L'9') || c == L'-';
                });
                locale.clear();
                for (const wchar_t c : tag) {
                    locale.push_back(static_cast<char>(c));
                }
            } else {
                fine = false;
            }
        }
        if (fine) {
            return checkScriptProject(fs::path(args[0]), json, locale);
        }
        return usage("gs check <folder> [--json] [--locale <tag>]");
    }
    if (verb == L"types") {
        if (args.size() == 1) {
            return writeProjectTypes(fs::path(args[0]));
        }
        return usage("gs types <folder>");
    }
    if (verb == L"run") {
        return runReplayCommand(args);
    }
    if (verb == L"test") {
        return runTestCommand(args);
    }
    return std::nullopt;
}

