package com.gamescrcpy.server.uhid;

import static com.gamescrcpy.server.uhid.UhidEventsTest.bytes;
import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.ByteBuffer;
import org.junit.jupiter.api.Test;

class HidDescriptorTest {

    static byte[] touchDescriptor() {
        final byte[] head = bytes(0x05, 0x0D, 0x09, 0x04, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x54, 0x15, 0x00, 0x25, 0x10,
                0x75, 0x08, 0x95, 0x01, 0x81, 0x02);
        final byte[] finger = bytes(0x09, 0x22, 0xA1, 0x02, 0x09, 0x42, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x01,
                0x81, 0x02, 0x75, 0x07, 0x81, 0x03, 0x09, 0x51, 0x25, 0x7F, 0x75, 0x08, 0x81, 0x02, 0x05, 0x01, 0x09,
                0x30, 0x09, 0x31, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0x05, 0x0D, 0xC0);
        final byte[] tail = bytes(0x85, 0x02, 0x09, 0x55, 0x25, 0x10, 0x75, 0x08, 0x95, 0x01, 0xB1, 0x02, 0xC0);
        final ByteBuffer all = ByteBuffer.allocate(head.length + 16 * finger.length + tail.length);
        all.put(head);
        for (int i = 0; i < 16; ++i) {
            all.put(finger);
        }
        all.put(tail);
        return all.array();
    }

    @Test
    void theTouchScreenAnswersItsContactCountMaximum() {
        final HidDescriptor descriptor = new HidDescriptor(touchDescriptor());
        assertTrue(descriptor.numbered());
        assertArrayEquals(bytes(2, 16), descriptor.featureReport(2));
        assertNull(descriptor.featureReport(1));
        assertNull(descriptor.featureReport(3));
    }

    static byte[] gamepadDescriptor() {
        return bytes(0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85, 0x01, 0x05, 0x09, 0x19, 0x01, 0x29, 0x10, 0x15, 0x00,
                0x25, 0x01, 0x75, 0x01, 0x95, 0x10, 0x81, 0x02, 0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x16, 0x00, 0x80,
                0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0xC0);
    }

    @Test
    void gamepadsAndJoysticksAreKnownByTheirApplication() {
        assertTrue(new HidDescriptor(gamepadDescriptor()).gamepad());
        assertTrue(new HidDescriptor(bytes(0x05, 0x01, 0x09, 0x04, 0xA1, 0x01, 0x09, 0x30, 0x75, 0x08, 0x95, 0x01,
                0x81, 0x02, 0xC0)).gamepad());
        assertFalse(new HidDescriptor(touchDescriptor()).gamepad());
        assertFalse(new HidDescriptor(bytes(0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x09, 0x05, 0xA1, 0x02, 0xC0,
                0xC0)).gamepad());
        assertFalse(new HidDescriptor(new byte[0]).gamepad());
    }

    @Test
    void anAnsweredReportCannotBeChangedByItsReader() {
        final HidDescriptor descriptor = new HidDescriptor(touchDescriptor());
        descriptor.featureReport(2)[1] = 0;
        assertArrayEquals(bytes(2, 16), descriptor.featureReport(2));
    }

    @Test
    void aDescriptorWithoutReportIdsIsUnnumbered() {
        final HidDescriptor keyboard = new HidDescriptor(bytes(0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x05, 0x07, 0x19,
                0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0xC0));
        assertFalse(keyboard.numbered());
        assertNull(keyboard.featureReport(0));

        final HidDescriptor unnumbered = new HidDescriptor(bytes(0x05, 0x0D, 0x09, 0x04, 0xA1, 0x01, 0x09, 0x55, 0x25,
                0x0A, 0x75, 0x08, 0x95, 0x01, 0xB1, 0x02, 0xC0));
        assertFalse(unnumbered.numbered());
        assertArrayEquals(bytes(10), unnumbered.featureReport(0));
    }

    @Test
    void aBrokenDescriptorIsReadWithoutFailing() {
        assertFalse(new HidDescriptor(new byte[0]).numbered());
        assertFalse(new HidDescriptor(bytes(0x85)).numbered());
        assertNull(new HidDescriptor(bytes(0x05, 0x0D, 0x95, 0xFF, 0x75, 0x00, 0x09, 0x55, 0xB1, 0x02))
                .featureReport(0));
        assertNull(new HidDescriptor(bytes(0x05, 0x0D, 0x97, 0xFF, 0xFF, 0xFF, 0xFF, 0x75, 0x08, 0x09, 0x55, 0xB1, 0x02))
                .featureReport(0));
        assertFalse(new HidDescriptor(bytes(0xFE, 0x02, 0x00, 0x85, 0x01)).numbered());
    }
}
